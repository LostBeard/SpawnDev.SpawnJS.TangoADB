// rebundle.cs - SpawnDev.SpawnJS.TangoADB bundle updater
//
// NOTE: named "rebundle" (not "update") on purpose - Windows' legacy UAC installer-detection
// heuristic force-elevates any executable named update.exe / setup.exe / install.exe, and
// `dotnet run` compiles the script to <name>.exe.
//
// Pulls the latest @yume-chan Tango ADB packages, bundles them into a single ESM file
// (wwwroot/tango-adb.js), copies the scrcpy runtime assets, and bakes the resolved
// @yume-chan/adb version into the library as a generated C# constant so it is readable
// through SpawnDev.SpawnJS.TangoADB (Tango.BundledLibraryVersion).
//
// This is NOT part of `dotnet build` - consumers and routine library builds need no Node
// toolchain. Run it deliberately to bump the bundled Tango version:
//
//     dotnet run rebundle.cs                 # install latest, rebundle, regenerate version
//     dotnet run rebundle.cs -- --no-install # rebundle from current node_modules only
//
// Requires: Node.js + npm + npx on PATH (esbuild is a devDependency of bundle/package.json).

using System.Diagnostics;
using System.Text;
using System.Text.Json;

// --- Paths (this script lives in <repoRoot>/bundle) ---
string bundleDir = AppContext.BaseDirectory;
// dotnet run resolves the script dir as cwd; prefer the script's own directory.
bundleDir = Directory.GetCurrentDirectory();
string repoRoot = Path.GetFullPath(Path.Combine(bundleDir, ".."));
string libDir = Path.Combine(repoRoot, "SpawnDev.SpawnJS.TangoADB");
string wwwroot = Path.Combine(libDir, "wwwroot");
string nodeModules = Path.Combine(bundleDir, "node_modules", "@yume-chan");
string bundleOut = Path.Combine(wwwroot, "tango-adb.js");
string genCs = Path.Combine(libDir, "TangoVersion.g.cs");
string claudeMd = Path.Combine(repoRoot, "CLAUDE.md");

bool noInstall = args.Contains("--no-install");

Directory.CreateDirectory(wwwroot);

// --- 1. Install latest packages ---
if (!noInstall)
{
    Console.WriteLine(">> npm install (pulling latest @yume-chan/* per package.json)");
    Run("npm", "install", bundleDir);
}
else
{
    Console.WriteLine(">> --no-install: bundling from current node_modules");
}

// --- 2. Bundle to a single ESM file ---
Console.WriteLine(">> esbuild -> wwwroot/tango-adb.js");
Run("npx", $"esbuild index.ts --bundle --format=esm --target=es2022 --outfile=\"{bundleOut}\"", bundleDir);

// --- 2b. Fetch the matching scrcpy server binary and commit it to wwwroot ---
// The version must match the scrcpy server protocol @yume-chan/scrcpy speaks (latest options = 3.3.x).
const string scrcpyServerVersion = "3.3.1";
string fetchScript = Path.Combine(nodeModules, "fetch-scrcpy-server", "bin", "fetch-server.js");
string serverBin = Path.Combine(nodeModules, "fetch-scrcpy-server", "server.bin");
if (File.Exists(fetchScript))
{
    Console.WriteLine($">> fetching scrcpy-server v{scrcpyServerVersion}");
    if (!File.Exists(serverBin)) Run("node", $"\"{fetchScript}\" {scrcpyServerVersion}", bundleDir);
    if (File.Exists(serverBin))
    {
        File.Copy(serverBin, Path.Combine(wwwroot, "scrcpy-server"), overwrite: true);
        Console.WriteLine(">> copied scrcpy-server -> wwwroot/scrcpy-server");
    }
    else Console.WriteLine(">> WARNING: scrcpy-server.bin not produced; Screen page will not work until it is present.");
}

// --- 3. Read resolved @yume-chan versions ---
var versions = new SortedDictionary<string, string>(StringComparer.Ordinal);
foreach (var dir in Directory.EnumerateDirectories(nodeModules))
{
    var pkgJson = Path.Combine(dir, "package.json");
    if (!File.Exists(pkgJson)) continue;
    using var doc = JsonDocument.Parse(File.ReadAllText(pkgJson));
    var name = doc.RootElement.GetProperty("name").GetString()!;
    var ver = doc.RootElement.GetProperty("version").GetString()!;
    versions[name] = ver;
}
string adbVersion = versions.TryGetValue("@yume-chan/adb", out var av) ? av : "unknown";
Console.WriteLine($">> @yume-chan/adb resolved to {adbVersion}");

// --- 4. Generate TangoVersion.g.cs (so the version is readable through the library) ---
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Generated by bundle/update.cs. Do not edit by hand.");
sb.AppendLine("// Records the @yume-chan package versions bundled into wwwroot/tango-adb.js.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("namespace SpawnDev.SpawnJS.TangoADB");
sb.AppendLine("{");
sb.AppendLine("    public partial class Tango");
sb.AppendLine("    {");
sb.AppendLine($"        /// <summary>The bundled @yume-chan/adb (Tango) version. Generated by bundle/update.cs.</summary>");
sb.AppendLine($"        public const string BundledLibraryVersion = \"{adbVersion}\";");
sb.AppendLine();
sb.AppendLine("        /// <summary>All bundled @yume-chan package versions (package name -> version).</summary>");
sb.AppendLine("        public static readonly System.Collections.Generic.IReadOnlyDictionary<string, string> BundledPackageVersions");
sb.AppendLine("            = new System.Collections.Generic.Dictionary<string, string>");
sb.AppendLine("        {");
foreach (var kv in versions)
    sb.AppendLine($"            [\"{kv.Key}\"] = \"{kv.Value}\",");
sb.AppendLine("        };");
sb.AppendLine("    }");
sb.AppendLine("}");
File.WriteAllText(genCs, sb.ToString());
Console.WriteLine($">> wrote {genCs}");

// --- 5. Record the version table into CLAUDE.md (audit trail) ---
if (File.Exists(claudeMd))
{
    const string startMark = "<!-- TANGO-VERSIONS:START -->";
    const string endMark = "<!-- TANGO-VERSIONS:END -->";
    var table = new StringBuilder();
    table.AppendLine(startMark);
    table.AppendLine("## Bundled @yume-chan versions");
    table.AppendLine();
    table.AppendLine("| Package | Version |");
    table.AppendLine("|---|---|");
    foreach (var kv in versions) table.AppendLine($"| {kv.Key} | {kv.Value} |");
    table.AppendLine(endMark);

    var content = File.ReadAllText(claudeMd);
    int s = content.IndexOf(startMark, StringComparison.Ordinal);
    int e = content.IndexOf(endMark, StringComparison.Ordinal);
    if (s >= 0 && e > s)
        content = content[..s] + table.ToString().TrimEnd() + content[(e + endMark.Length)..];
    else
        content = content.TrimEnd() + "\n\n" + table.ToString();
    File.WriteAllText(claudeMd, content);
    Console.WriteLine(">> updated CLAUDE.md version table");
}

Console.WriteLine(">> Done. Bundle + scrcpy-server + version constant refreshed.");
Console.WriteLine(">> NOTE: the TinyH264 (software) decoder additionally needs its WASM worker emitted as a");
Console.WriteLine(">>       separate asset; the WebCodecs decoder (primary path) needs no extra asset.");

// --- helpers ---
static void Run(string file, string arguments, string workingDir)
{
    // On Windows, npm/npx are .cmd shims - invoke via cmd.exe for reliable resolution.
    var isWin = OperatingSystem.IsWindows();
    var psi = new ProcessStartInfo
    {
        FileName = isWin ? "cmd.exe" : file,
        Arguments = isWin ? $"/c {file} {arguments}" : arguments,
        WorkingDirectory = workingDir,
        UseShellExecute = false,
    };
    var p = Process.Start(psi)!;
    p.WaitForExit();
    if (p.ExitCode != 0) throw new Exception($"{file} {arguments} failed with exit code {p.ExitCode}");
}
